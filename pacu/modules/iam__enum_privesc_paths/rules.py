"""Known IAM privilege-escalation primitives used by the offline scanner.

Each rule lists the actions that must be usable together. Optional actions are
shown in the report as context but do not make a path possible by themselves.
"""
from __future__ import annotations

from typing import Any, Dict, List, Tuple


def _rule(
    method: str,
    title: str,
    severity: str,
    identity_types: Tuple[str, ...],
    required_actions: List[str],
    description: str,
    impact: str,
    optional_actions: List[str] | None = None,
) -> Dict[str, Any]:
    return {
        "method": method,
        "title": title,
        "severity": severity,
        "identity_types": list(identity_types),
        "required_actions": required_actions,
        "optional_actions": optional_actions or [],
        "description": description,
        "impact": impact,
    }


